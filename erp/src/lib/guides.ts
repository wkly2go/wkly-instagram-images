/** 질문 낱말과 안내 맞추기 (제목 · 낱말 겹침) — 높은 순 최대 n 개 */
export function findGuides(question: string, n = 3): Guide[] {
  const q = question.toLowerCase().replace(/\s+/g, ' ')
  const scored = GUIDES.map(g => {
    let s = 0
    for (const k of g.keywords) if (q.includes(k.toLowerCase())) s += k.length > 2 ? 3 : 2
    for (const w of g.title.split(/[\s·]+/)) if (w.length > 1 && q.includes(w.toLowerCase())) s += 1
    return { g, s }
  }).filter(x => x.s > 0)
  scored.sort((a, b) => b.s - a.s)
  return scored.slice(0, n).map(x => x.g)
}

