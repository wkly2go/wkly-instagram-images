export function getSalesPlaybook(draft: SalesPlaybookDraft): SalesPlaybookGuide {
  const track: SalesTrack = draft.source === '나라장터' ? 'public' : draft.division === 'AR' ? 'space' : 'content'
  const guide = (track === 'public' ? PUBLIC : track === 'space' ? SPACE : CONTENT)[draft.stage]
  const handoff = draft.stage !== '수주' ? [] : [
    '계약·발주 확정 근거와 최종 합의 버전',
    track === 'space' ? '최종 도면·사양·견적·현장 조건·공정표' : track === 'public' ? '공고·정정·질의답변·최종 과업·제안서·계약 자료' : '최종 제작물·채널·사용 권리·고객 승인 절차',
    '수행 담당자·고객 연락 창구·착수·검수·결제 일정',
    draft.project_id ? '연결 프로젝트의 회사·거래처와 인계 자료 일치 여부 확인' : '프로젝트 메뉴에서 같은 수행 회사·거래처의 프로젝트 준비 후 연결',
  ]
  return {
    ...guide, actions: [...guide.actions], evidence: [...guide.evidence], track, stage: draft.stage,
    trackLabel: track === 'public' ? '나라장터·공공 입찰' : track === 'space' ? '공간·인테리어' : '콘텐츠·광고',
    nextStep: NEXT[draft.stage], handoff,
    caution: track === 'public'
      ? '공고별 최신 원문과 정정·질의 답변이 기준입니다. 낙찰·우선협상 통보는 계약 체결과 구분합니다. 이 안내는 자격 충족·제출·수주를 판정하지 않습니다.'
      : '확인 자료를 검토한 뒤 담당자가 진행 단계를 변경합니다. 이 안내는 완료 여부나 수주 확률을 판정하지 않습니다.',
  }
}

/** Only next_action may change, and an existing different action requires confirmation. */
export function salesPlaybookActionPatch(draft: SalesPlaybookDraft, confirmReplace: (message: string) => boolean, disabled = false): Pick<SalesDraft, 'next_action'> | null {
  if (disabled) return null
  const next = getSalesPlaybook(draft).nextAction
  if (draft.next_action === next) return null
  if (draft.next_action.trim() && !confirmReplace('입력한 다음 행동을 이 단계의 예시로 바꿀까요? 연락일과 진행 단계는 유지됩니다.')) return null
  return { next_action: next }
}
