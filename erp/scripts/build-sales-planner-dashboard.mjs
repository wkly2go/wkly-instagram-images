import {build} from 'esbuild'
import {readFile,writeFile} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'
const entry=fileURLToPath(new URL('../supabase/functions/sales-planner/index.ts',import.meta.url))
const path=new URL('../supabase/deploy/sales-planner-dashboard.ts',import.meta.url)
const result=await build({entryPoints:[entry],bundle:true,write:false,platform:'neutral',format:'esm',packages:'external',target:'es2022',logLevel:'silent'})
const output='// Generated by scripts/build-sales-planner-dashboard.mjs\n'+result.outputFiles[0].text
if(process.argv.includes('--check')){if(await readFile(path,'utf8')!==output)throw new Error('Rebuild sales-planner dashboard source')}else await writeFile(path,output)
