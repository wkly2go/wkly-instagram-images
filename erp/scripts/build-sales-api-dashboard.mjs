import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { createHash } from 'node:crypto'
import { build } from 'esbuild'

const root = new URL('../', import.meta.url)
export const dashboardFile = new URL('supabase/deploy/sales-api-dashboard.ts', root)

export async function buildDashboardSource() {
  const { outputFiles } = await build({
    entryPoints: ['supabase/functions/sales-api/index.ts'],
    absWorkingDir: fileURLToPath(root),
    bundle: true,
    write: false,
    format: 'esm',
    target: 'es2022',
    external: ['npm:*'],
    legalComments: 'none',
  })
  const code = outputFiles[0].text
  const hash = createHash('sha256').update(code).digest('hex')
  return `// @ts-nocheck -- Generated JavaScript; type check the TypeScript source entry point.\n// Generated by scripts/build-sales-api-dashboard.mjs.\n// Bundle SHA-256: ${hash}\n// Paste into sales-api / index.ts. Preserve Supabase JWT verification.\n\n${code}`
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const code = await buildDashboardSource()
  if (process.argv.includes('--check')) {
    if (await readFile(dashboardFile, 'utf8') !== code) throw new Error('sales-api Dashboard file is stale')
    console.log('sales-api Dashboard file matches its sources.')
  } else {
    await writeFile(dashboardFile, code)
    console.log('Wrote supabase/deploy/sales-api-dashboard.ts')
  }
}
