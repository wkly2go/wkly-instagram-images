import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import ts from 'typescript'

const root = new URL('../', import.meta.url)
export const dashboardFile = new URL('supabase/deploy/growth-ai-dashboard.ts', root)
const sources = ['policy.ts', 'handler.ts', 'index.ts']
const allowedImports = new Map([['handler.ts', './policy.ts'], ['index.ts', './handler.ts']])

export async function buildDashboardSource() {
  const texts = await Promise.all(sources.map(name => readFile(new URL(`supabase/functions/growth-ai/${name}`, root), 'utf8')))
  const hash = createHash('sha256').update(sources.map((name, i) => `${name}\0${texts[i]}`).join('\0')).digest('hex')
  const combined = texts.map((text, i) => {
    const name = sources[i], parsed = ts.createSourceFile(name, text, ts.ScriptTarget.Latest, true)
    const localImports = parsed.statements.filter(s => ts.isImportDeclaration(s) && s.moduleSpecifier.text.startsWith('.'))
    const expected = allowedImports.get(name)
    if (localImports.length !== (expected ? 1 : 0) || localImports.some(s => s.moduleSpecifier.text !== expected)) throw new Error(`Review local imports before building ${name}`)
    for (const statement of [...localImports].reverse()) text = text.slice(0, statement.getStart(parsed)) + text.slice(statement.end)
    return `// Source: supabase/functions/growth-ai/${name}\n${text.trim()}\n`
  })
  return `// Generated by scripts/build-growth-ai-dashboard.mjs. Edit the original sources, then rebuild.\n// Source SHA-256: ${hash}\n// Paste this whole file into growth-ai / index.ts in the Supabase Dashboard.\n\n${combined.join('\n')}`
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const source = await buildDashboardSource()
  if (process.argv.includes('--check')) {
    if (await readFile(dashboardFile, 'utf8') !== source) throw new Error('Dashboard code is stale; rebuild before deployment.')
    console.log('Dashboard code matches source files.')
  } else {
    await mkdir(new URL('supabase/deploy/', root), { recursive: true })
    await writeFile(dashboardFile, source)
    console.log('Wrote supabase/deploy/growth-ai-dashboard.ts')
  }
}
